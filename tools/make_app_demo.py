"""
Writes src/nc/demo-complex.js, the app's "Sync example", from
tools/example/complex: the synced H and V programs plus each op's time from
the op list, split the same way the planner splits it.

    python tools/make_app_demo.py      (after changing the complex example)
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sync_insert as si  # noqa: E402
import sync_plan as sp  # noqa: E402

COMPLEX = os.path.join(HERE, "example", "complex")
OUT = os.path.join(HERE, "..", "src", "nc", "demo-complex.js")


def main():
    def read(name):
        with open(os.path.join(COMPLEX, name)) as f:
            return f.read()

    ops_text = read("ops.txt")
    problems = si.Problems()
    h_marked, v_marked, timeline = si.mark(ops_text, read("H_raw.nc").splitlines(), read("V_raw.nc").splitlines(), problems)
    h_sync, v_sync = si.to_code(h_marked, v_marked, problems)
    if problems.errors:
        print("\n".join(problems.errors))
        return 1

    h, v, _ = sp.parse_ops(ops_text)
    # pre = the part of the op that happens before the spindle may cut:
    #   H: the B move / tool change between (WAIT BEFORE) and (WAIT AFTER)
    #   V: the tool change, which runs before its (WAIT)
    times = {
        "h": [{"seconds": op["seconds"], "pre": sp.event_lockout(h[i - 1] if i else None, op) or 0} for i, op in enumerate(h)],
        "v": [{"seconds": op["seconds"], "pre": sp.v_tool_change(v, i)} for i, op in enumerate(v)],
    }
    planned = float(timeline[-1].split()[0].rstrip("s"))

    js = """/**
 * The "Sync example": tools/example/complex after sync_insert.py, with the op
 * list's times. Generated by tools/make_app_demo.py; do not edit by hand.
 *
 * 10 H and 12 V ops bouncing between part 1 (G54, #1003, W1) and part 2
 * (G55, #1004, W2), 5 B events. With these times the app's schedule matches
 * the planner's cycle (PLANNED_SECONDS).
 */
export const SYNC_EXAMPLE = {
  sources: %s,
  filenames: { h: 'FAM_2H.nc', v: 'FAM_2V.nc' },
  times: %s,
};

export const PLANNED_SECONDS = %s;
""" % (
        json.dumps({"h": "\n".join(h_sync) + "\n", "v": "\n".join(v_sync) + "\n"}, indent=2).replace("\n", "\n  "),
        json.dumps(times),
        json.dumps(planned),
    )
    with open(OUT, "w", newline="\n") as f:
        f.write(js)
    print("Wrote " + os.path.relpath(OUT) + "  (planned cycle {:.0f} s)".format(planned))
    return 0


if __name__ == "__main__":
    sys.exit(main())
